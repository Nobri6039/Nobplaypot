# Nobplaypot payload signing script.
#
# What it does:
#   1. On first run it creates an RSA-2048 private key at tools\private-key.txt.
#      Keep that file secret; never commit or ship it.
#   2. Writes pubkey.h with the public key blob that is compiled into the exe.
#      If the key changes you must rebuild the exe.
#   3. Hashes launch.json, python-runtime, the .py/.pyw files under Bin and
#      vlc-runtime, then writes Bin\payload.manifest.
#   4. Signs the manifest with the private key and writes Bin\payload.sig.
#
# Run this again every time you update the payload (py files, runtime, VLC),
# otherwise the exe will reject the new files.
#
# Usage:
#   powershell -ExecutionPolicy Bypass -File tools\sign.ps1

#Requires -Version 5.1
param([string]$Root = (Split-Path -Parent $PSScriptRoot))

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path -LiteralPath $Root).Path
$bin = Join-Path $root 'Bin'
$tools = $PSScriptRoot
if (-not (Test-Path -LiteralPath $bin)) {
    throw "Bin directory not found: $bin"
}

# ---------------------------------------------------------------- key
$keyPath = Join-Path $tools 'private-key.xml'
if (-not (Test-Path -LiteralPath $keyPath)) {
    $rsa = [System.Security.Cryptography.RSA]::Create(2048)
    [IO.File]::WriteAllText($keyPath,
        $rsa.ToXmlString($true),
        (New-Object Text.UTF8Encoding($false)))
    Write-Host "Generated a new private key: $keyPath"
    Write-Host "Keep it secret. Do not commit it or send it to anyone." -ForegroundColor Yellow
} else {
    $rsa = [System.Security.Cryptography.RSA]::Create()
    $rsa.FromXmlString((Get-Content -Raw -LiteralPath $keyPath))
}

# ---------------------------------------------------------------- public key header
$p = $rsa.ExportParameters($false)
$mod = $p.Modulus
$exp = $p.Exponent
$blob = New-Object System.Collections.Generic.List[byte]
$blob.AddRange([byte[]](0x52, 0x53, 0x41, 0x31))          # BCRYPT_RSAPUBLIC_MAGIC
$blob.AddRange([BitConverter]::GetBytes([uint32]$rsa.KeySize))
$blob.AddRange([BitConverter]::GetBytes([uint32]$exp.Length))
$blob.AddRange([BitConverter]::GetBytes([uint32]$mod.Length))
$blob.AddRange([BitConverter]::GetBytes([uint32]0))
$blob.AddRange([BitConverter]::GetBytes([uint32]0))
$blob.AddRange($exp)
$blob.AddRange($mod)
$hex = ($blob | ForEach-Object { '0x{0:X2}' -f $_ }) -join ', '
$header = @"
// Generated by tools/sign.ps1. Do not edit by hand.
#pragma once
static const unsigned char kPublicKey[] = {
    $hex
};
static const unsigned int kPublicKeySize = static_cast<unsigned int>(sizeof(kPublicKey));
"@
$utf8NoBom = New-Object Text.UTF8Encoding($false)
[IO.File]::WriteAllText((Join-Path $root 'pubkey.h'), $header, $utf8NoBom)

# ---------------------------------------------------------------- file list
$files = New-Object System.Collections.Generic.List[object]
$rootLen = $root.Length + 1
function Add-PayloadFile {
    param([string]$Relative)
    $full = Join-Path $root $Relative
    if (-not (Test-Path -LiteralPath $full -PathType Leaf)) { return }
    $hash = (Get-FileHash -LiteralPath $full -Algorithm SHA256).Hash.ToLowerInvariant()
    $files.Add([ordered]@{
        path   = ($Relative -replace '\\', '/')
        sha256 = $hash
    })
}

Add-PayloadFile 'Bin/launch.json'

$runtime = Join-Path $root 'python-runtime'
if (Test-Path -LiteralPath $runtime) {
    Get-ChildItem -LiteralPath $runtime -Recurse -File | ForEach-Object {
        Add-PayloadFile ($_.FullName.Substring($rootLen))
    }
}

Get-ChildItem -LiteralPath $bin -File | Where-Object {
    $_.Extension -in '.py', '.pyw'
} | ForEach-Object {
    Add-PayloadFile ($_.FullName.Substring($rootLen))
}

$vlc = Join-Path $root 'vlc-runtime'
if (Test-Path -LiteralPath $vlc) {
    Get-ChildItem -LiteralPath $vlc -Recurse -File | ForEach-Object {
        Add-PayloadFile ($_.FullName.Substring($rootLen))
    }
}

$manifestText = ([ordered]@{
    schema = 1
    files  = $files
}) | ConvertTo-Json -Depth 5
$manifestPath = Join-Path $bin 'payload.manifest'
[IO.File]::WriteAllText($manifestPath, $manifestText, $utf8NoBom)

# ---------------------------------------------------------------- signature
$bytes = [IO.File]::ReadAllBytes($manifestPath)
$signature = $rsa.SignData(
    $bytes,
    [System.Security.Cryptography.HashAlgorithmName]::SHA256,
    [System.Security.Cryptography.RSASignaturePadding]::Pkcs1)
[IO.File]::WriteAllText((Join-Path $bin 'payload.sig'),
    [Convert]::ToBase64String($signature),
    [Text.Encoding]::ASCII)

Write-Host "Wrote: $manifestPath"
Write-Host "Wrote: $(Join-Path $bin 'payload.sig')"
Write-Host "Wrote: $(Join-Path $root 'pubkey.h')"
Write-Host "Files: $($files.Count)"
